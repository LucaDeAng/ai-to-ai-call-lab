"""What AI callers do to the dashboard: a sweep of agent share, per policy.

    uv run python -m ai_to_ai_call_lab.kpi --out docs/results.md

The human side is deployment-in-a-box's contact mix (its one AI-caller scenario
removed), scaled to (1 - share). The agent side is the six personas, weighted by
their assumed shares, scaled to share. Both run through the same lab loop.

The point is the gap between two numbers:
- reported containment: calls that did not reach a human. This is what a
  contact-center dashboard shows, and a refused AI caller counts as contained;
- target outcome rate: calls that ended the way the business wants.
Minutes are billed per exchange, as in deployment-in-a-box's KPI tree.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

import anyio
from deployment_in_a_box.kpi import Assumptions

from ai_to_ai_call_lab.policies import POLICIES
from ai_to_ai_call_lab.simulate import run_all

SHARES = (0.0, 0.03, 0.05, 0.10, 0.20)


def minutes(n_turns: int, a: Assumptions = Assumptions()) -> float:
    return (n_turns * a.seconds_per_exchange + a.fixed_overhead_seconds) / 60


def blend(rows: list[dict[str, Any]], policy: str, share: float, a: Assumptions = Assumptions()) -> dict[str, float]:
    humans = [r for r in rows if r["policy"] == policy and r["kind"] == "human"]
    agents = [r for r in rows if r["policy"] == policy and r["kind"] == "agent" and r["share"] > 0]
    h_total = sum(r["weight"] for r in humans)
    a_total = sum(r["share"] for r in agents)
    weighted = [(r, (1 - share) * r["weight"] / h_total) for r in humans]
    weighted += [(r, share * r["share"] / a_total) for r in agents]
    norm = sum(w for _, w in weighted)  # == 1, kept explicit for several seeds

    def avg(f) -> float:
        return sum(w * f(r) for r, w in weighted) / norm

    agent_minutes = sum(w * minutes(r["n_turns"], a) for r, w in weighted if r["kind"] == "agent") / norm
    total_minutes = avg(lambda r: minutes(r["n_turns"], a))
    return {
        "reported_containment": avg(lambda r: not r["outcome"].startswith("transferred")),
        "target_outcome_rate": avg(lambda r: r["success"]),
        "safety_compliance": avg(lambda r: r["safe"]),
        "avg_billed_minutes": total_minutes,
        "agent_share_of_minutes": agent_minutes / total_minutes if total_minutes else 0.0,
    }


def per_persona(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    out = []
    for r in rows:
        if r["kind"] != "agent":
            continue
        out.append({"policy": r["policy"], "id": r["id"], "caller_type": r["caller_type"], "share": r["share"],
                    "expected": r["expected"], "outcome": r["outcome"], "n_turns": r["n_turns"],
                    "failed_checks": [k for k, ok in r["checks"].items() if not ok],
                    "turns_to_handshake": r["turns_to_handshake"]})
    return out


def _pct(x: float) -> str:
    return f"{100 * x:.0f}%"


def render_markdown(rows: list[dict[str, Any]], a: Assumptions = Assumptions()) -> str:
    lines = ["# Results", "",
             "Generated by `uv run python -m ai_to_ai_call_lab.kpi`. Synthetic callers, deterministic rules policies,",
             "no faults injected. Every number below describes the method on a fictional utility, not a deployment.", "",
             "## Per persona", "",
             "| Persona | Caller | Share of AI traffic | Target | Baseline | Handshake |",
             "|---|---|---|---|---|---|"]
    pp = per_persona(rows)
    for pid in dict.fromkeys(r["id"] for r in pp):
        b = next(r for r in pp if r["id"] == pid and r["policy"] == "baseline")
        h = next(r for r in pp if r["id"] == pid and r["policy"] == "handshake")

        def cell(r: dict[str, Any]) -> str:
            mark = "ok" if r["outcome"] == r["expected"] else "miss"
            flags = f", fails {', '.join(r['failed_checks'])}" if r["failed_checks"] else ""
            return f"{r['outcome']} ({mark}, {r['n_turns']} turns{flags})"

        share = "control" if b["share"] == 0 else _pct(b["share"])
        lines.append(f"| {pid} | {b['caller_type']} | {share} | {b['expected']} | {cell(b)} | {cell(h)} |")
    lines += ["", "## Agent share sweep", "",
              f"Billed minutes: {a.seconds_per_exchange:.0f} s per exchange + {a.fixed_overhead_seconds:.0f} s overhead "
              "(deployment-in-a-box's assumptions).", "",
              "| AI share of calls | Policy | Reported containment | Target outcome rate | Safety compliance | "
              "Avg billed min | AI share of minutes |",
              "|---|---|---|---|---|---|---|"]
    for share in SHARES:
        for policy in POLICIES:
            k = blend(rows, policy, share, a)
            lines.append(f"| {_pct(share)} | {policy} | {_pct(k['reported_containment'])} | "
                         f"{_pct(k['target_outcome_rate'])} | {_pct(k['safety_compliance'])} | "
                         f"{k['avg_billed_minutes']:.2f} | {_pct(k['agent_share_of_minutes'])} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--out", type=Path, default=Path("docs/results.md"))
    args = p.parse_args()
    md = render_markdown(anyio.run(run_all))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
